"""Create clearly labeled synthetic input and its actual plotting data."""
import csv
import json
from pathlib import Path
import math


def main():
    root=Path(__file__).resolve().parents[1]/"examples/computers-and-structures"
    root.mkdir(parents=True,exist_ok=True)
    source=root/"manuscript.md"
    if source.exists(): raise FileExistsError(source)
    values=[(i/10,math.exp(-.25*i/10)*math.sin(i/10)) for i in range(101)]
    with (root/"fixture-data.csv").open("x",encoding="utf-8",newline="") as f:
        writer=csv.writer(f); writer.writerow(["time_s","synthetic_response"]); writer.writerows(values)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family":"Times New Roman","font.size":10})
    fig,ax=plt.subplots(figsize=(5,2.5))
    ax.plot([v[0] for v in values],[v[1] for v in values],color="black",linewidth=1)
    ax.set(xlabel="Time (s)",ylabel="Synthetic response")
    fig.tight_layout(); fig.savefig(root/"response.png",dpi=300); fig.savefig(root/"response.pdf"); plt.close(fig)
    abstract="This synthetic manuscript exercises a local document workflow. It checks template formatting, editable equations, figure and table numbering, and cross-references. The numerical values are test fixtures and are not research results."
    metadata={"abstract":abstract,"keywords":["Document workflow","Editable equations","Cross-references"],
              "fixture_only":True,"figure_sources":{"1":"response.pdf"}}
    (root/"metadata.json").write_text(json.dumps(metadata,indent=2),encoding="utf-8")
    source.write_text("""---
title: Editable manuscript workflow validation
author: Workflow Test Author
date: ''
---

**Synthetic integration fixture**

Affiliation: Local software validation, not a submitted research manuscript.

## Abstract {.unnumbered}

"""+abstract+"""

Keywords: Document workflow; Editable equations; Cross-references

# 1 Introduction

The input table and response plot use synthetic data. Both appear in the manuscript with numbered captions.

# 2 Methods

The editable dynamics equation is included to exercise mathematical notation and its reference, Eq. ([[REF dynamics]]).

$\\mathbf{M}\\ddot{\\mathbf{x}}+\\mathbf{C}\\dot{\\mathbf{x}}+\\mathbf{K}\\mathbf{x}=\\mathbf{f}(t)$ [[EQNO dynamics]]

The matrix is an independent conversion fixture.

$\\mathbf{A}=\\begin{bmatrix}1&2\\\\3&4\\end{bmatrix}$ [[EQNO matrix]]

# 3 Fixture output

Figure [[REF response]] comes from fixture-data.csv generated by make_example.py. It contains synthetic values.

![Synthetic response fixture](response.png){width=13cm}

[[CAPTION Figure response|Synthetic response used for software validation]]

The values in Table [[REF results]] are editable Word table cells.

[[CAPTION Table results|Synthetic fixture values]]

| Case | Value |
|:-----|------:|
| A | 1.25 |
| B | 2.50 |

# 4 Conclusion

This document demonstrates software behavior only. It reports no scientific findings.
""",encoding="utf-8")
    print(source)


if __name__=="__main__": main()
