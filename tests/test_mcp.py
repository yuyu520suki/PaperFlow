"""Real SDK client, stdio transport, persisted jobs and a host-reviewed edit."""
import asyncio
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

from paperflow import cli
from paperflow.gui import mcp_configuration


class MCPTests(unittest.IsolatedAsyncioTestCase):
    async def test_gui_configuration_starts_public_cli(self):
        if sys.platform == "win32":
            # A desktop shortcut may launch pythonw, which has no console streams.
            # Verify the configuration generated by that exact interpreter.
            with tempfile.TemporaryDirectory() as tmp:
                destination = Path(tmp) / "configuration.json"
                script = (
                    "import json,sys; from pathlib import Path; "
                    "from paperflow.gui import mcp_configuration; "
                    "Path(sys.argv[1]).write_text(json.dumps(mcp_configuration()), encoding='utf-8')"
                )
                await asyncio.to_thread(
                    subprocess.run,
                    [str(Path(sys.executable).with_name("pythonw.exe")), "-s", "-X", "utf8", "-c", script, str(destination)],
                    cwd=Path(__file__).resolve().parents[1], check=True, timeout=30,
                )
                config = json.loads(destination.read_text(encoding="utf-8"))["mcpServers"]["paperflow"]
                self.assertEqual(Path(config["command"]).resolve(), Path(sys.executable).with_name("python.exe").resolve())
        else:
            config = mcp_configuration()["mcpServers"]["paperflow"]
        params = StdioServerParameters(**config)
        async with stdio_client(params) as pipes, ClientSession(*pipes) as client:
            initialized = await client.initialize()
            self.assertEqual(initialized.serverInfo.name, "PaperFlow")
            listed = await client.list_tools()
            self.assertEqual({tool.name for tool in listed.tools},
                             {"capabilities", "command_help", "start_cli", "list_jobs", "job_status",
                              "cancel_job", "read_text", "write_text"})

    async def test_persistent_jobs_and_offline_host_review_over_stdio(self):
        project = Path(__file__).resolve().parents[1]
        with tempfile.TemporaryDirectory() as tmp:
            workspace = Path(tmp)
            args = ["-s", "-X", "utf8", "-m", "paperflow.mcp_server", "--workspace", str(workspace)]
            params = StdioServerParameters(command=sys.executable, args=args, cwd=workspace,
                                           env={"PYTHONPATH": str(project), "PYTHONNOUSERSITE": "1"})

            async def call(client, name, **kwargs):
                response = await client.call_tool(name, kwargs)
                self.assertFalse(response.isError, response.content)
                return response.structuredContent

            async def finish(client, job_id):
                async with asyncio.timeout(30):
                    while True:
                        status = await call(client, "job_status", job_id=job_id, tail_chars=100)
                        if status["status"] in {"succeeded", "failed", "cancelled"} and status["worker_alive"] is False:
                            return status
                        await asyncio.sleep(0.05)

            async with stdio_client(params) as pipes, ClientSession(*pipes) as client:
                await client.initialize()
                catalog = await call(client, "capabilities")
                command_names = {entry["name"] for entry in catalog["commands"]}
                self.assertEqual(command_names | {"mcp", "gui"}, set(cli.build_parser()._subparsers._group_actions[0].choices))
                response = await client.call_tool("command_help", {"command": "run"})
                self.assertIn("--template", response.content[0].text)
                self.assertTrue((await client.call_tool("start_cli", {"args": ["mcp"]})).isError)
                original = "It is worth noting that the measured displacement was 12.5 mm."
                await call(client, "write_text", path="原稿.txt", text=original)
                self.assertTrue((await client.call_tool("write_text", {"path": "原稿.txt", "text": "another file"})).isError)
                started = await call(client, "start_cli", args=["polish-plan", "原稿.txt", "--output-dir", "plan"])
                job_id = started["job_id"]
                first = await finish(client, job_id)
                self.assertEqual(first["status"], "succeeded", first)
            # Reconnect and use the persisted result from the first client.
            async with stdio_client(params) as pipes, ClientSession(*pipes) as client:
                await client.initialize()
                first = await finish(client, job_id)
                self.assertEqual(first["status"], "succeeded", first)
                plan = json.loads((await call(client, "read_text", path="plan/plan.json"))["text"])
                paragraph = plan["paragraphs"][0]
                paragraph["accepted"] = True
                paragraph["proposed_text"] = paragraph["text"].replace("It is worth noting that the", "The")
                await call(client, "write_text", path="人工审阅.json", text=json.dumps(plan, ensure_ascii=False))
                applied = await call(client, "start_cli", args=["polish-apply", "原稿.txt", "人工审阅.json", "修改稿.txt"])
                last = await finish(client, applied["job_id"])
                self.assertEqual(last["status"], "succeeded", last["stderr"])
                self.assertEqual(last["result"]["accepted_changes"], 1)
                self.assertEqual((await call(client, "read_text", path="修改稿.txt"))["text"],
                                 "The measured displacement was 12.5 mm.")
                self.assertEqual((await call(client, "read_text", path="原稿.txt"))["text"], original)
                jobs = await client.call_tool("list_jobs", {"limit": 2})
                self.assertIn(job_id, json.dumps(jobs.structuredContent))

                example = project / "examples/content-review"
                for name in ("manuscript.md", "evidence.json"):
                    (workspace / name).write_bytes((example / name).read_bytes())
                prepared = await call(client, "start_cli", args=["content-plan", "manuscript.md", "--evidence", "evidence.json",
                                                                  "--output-dir", "content"])
                result = await finish(client, prepared["job_id"])
                self.assertEqual(result["status"], "succeeded", result)
                self.assertFalse(result["result"]["remote_requests_performed"])
                content = json.loads((await call(client, "read_text", path="content/review-plan.json"))["text"])
                self.assertEqual(content["findings"], [])
                reviewed_example = json.loads((example / "review-plan.json").read_text(encoding="utf-8"))
                content["findings"] = reviewed_example["findings"]
                await call(client, "write_text", path="content-reviewed.json", text=json.dumps(content, ensure_ascii=False))
                checked = await call(client, "start_cli", args=["content-check", "manuscript.md", "content-reviewed.json"])
                result = await finish(client, checked["job_id"])
                self.assertEqual(result["status"], "succeeded", result)
                self.assertEqual(result["result"]["adoptable_count"], 1)
                blocked = next(finding["id"] for finding in result["result"]["findings"] if not finding["adoptable"])
                args = ["content-apply", "manuscript.md", "content-reviewed.json", "content-revised.md", "--accept"]
                rejected = await call(client, "start_cli", args=[*args, blocked])
                self.assertEqual((await finish(client, rejected["job_id"]))["status"], "failed")
                self.assertFalse((workspace / "content-revised.md").exists())
                applied = await call(client, "start_cli", args=[*args, "demo-peak-displacement"])
                result = await finish(client, applied["job_id"])
                self.assertEqual(result["status"], "succeeded", result)
                self.assertEqual(result["result"]["accepted_ids"], ["demo-peak-displacement"])
                revised = (await call(client, "read_text", path="content-revised.md"))["text"]
                self.assertIn("在本台试验台的预设激励下，开启控制器后，峰值位移从 12.50 mm 降至 9.75 mm", revised)
                self.assertIn("该控制器可以将任意类型结构的疲劳寿命提高 50%", revised)
                self.assertEqual((workspace / "manuscript.md").read_bytes(), (example / "manuscript.md").read_bytes())


if __name__ == "__main__":
    unittest.main()
